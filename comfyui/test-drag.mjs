 await page.evaluate(video=>{const app=window.comfyAPI.app.app;window.v=LiteGraph.createNode('LoadVideo');app.graph.add(v);v.pos=[700,140];v.setSize([420,180]);const w=v.widgets.find(w=>w.name==='file');w.value='topview3d/exports/'+video;w.callback(w.value)},video)
 await page.waitForFunction(()=>v.videoContainer?.querySelector('video')?.videoWidth>0)
 await page.waitForTimeout(800)
 const dimensions=await page.evaluate(()=>{const video=v.videoContainer.querySelector('video');return {w:video.clientWidth,h:video.clientHeight,vw:video.videoWidth,vh:video.videoHeight,size:[...v.size],widgets:v.widgets.map(w=>({name:w.name,y:w.y,height:w.computedHeight}))}})
 console.log(dimensions)
 assert.ok(Math.abs(dimensions.w/dimensions.h-dimensions.vw/dimensions.vh)<0.04)
 await drag('video','v')
 const videoBounds=await page.locator('video').boundingBox()
 await page.mouse.click(videoBounds.x+25,videoBounds.y+videoBounds.height-32)

 await page.waitForTimeout(300)
 assert.equal(await page.locator('video').evaluate(v=>v.paused),false)
 await page.locator('video').evaluate(v=>v.pause())
 await page.evaluate(()=>v.setSize([520,180]))
 await page.waitForTimeout(400)
 const resized=await page.locator('video').evaluate(video=>({w:video.clientWidth,h:video.clientHeight,ratio:video.videoWidth/video.videoHeight}))
 assert.ok(Math.abs(resized.w/resized.h-resized.ratio)<0.04)
 await page.screenshot({path:'comfyui/test-results/drag-video.png'})
 await page.evaluate(async()=>{const app=window.comfyAPI.app.app;await app.loadGraphData(app.graph.serialize());window.v=app.graph._nodes.find(n=>n.type==='LoadVideo')})
 await page.waitForFunction(()=>v.videoContainer?.querySelector('video')?.videoWidth>0)
 await page.waitForTimeout(600)
 await drag('video','v')
 const image=files.find(f=>f.endsWith('.png'));assert.ok(image)
 await page.evaluate(image=>{const app=window.comfyAPI.app.app;window.i=LiteGraph.createNode('LoadImage');app.graph.add(i);i.pos=[150,500];const w=i.widgets.find(w=>w.name==='image');w.value='topview3d/exports/'+image;w.callback(w.value)},image)
